/**
 * Generates the VAPID key pair Web Push needs and appends it to .env.local.
 *
 * Idempotent: if VAPID_PUBLIC_KEY is already in .env.local it leaves the file
 * alone. Regenerating keys invalidates every existing browser subscription,
 * so it should not happen by accident.
 *
 *   node scripts/generate-vapid-keys.mjs
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import webpush from "web-push";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const envPath = join(root, ".env.local");

const current = existsSync(envPath) ? readFileSync(envPath, "utf8") : "";

if (current.includes("VAPID_PUBLIC_KEY=")) {
  console.log("VAPID keys already present in .env.local — leaving them as they are.");
  console.log("Delete the VAPID_* lines first if you really mean to rotate them");
  console.log("(every device would have to re-subscribe).");
  process.exit(0);
}

const { publicKey, privateKey } = webpush.generateVAPIDKeys();

const block = [
  "",
  "# Web Push (community notifications) — generated by scripts/generate-vapid-keys.mjs",
  `VAPID_PUBLIC_KEY=${publicKey}`,
  `VAPID_PRIVATE_KEY=${privateKey}`,
  "VAPID_SUBJECT=mailto:info@easywaygerman.com",
  "",
].join("\n");

writeFileSync(envPath, current + block, "utf8");

console.log("VAPID keys written to .env.local.");
console.log("Restart the dev server so the new environment variables load.");
